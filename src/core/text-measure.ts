type PlacedBox = { left: number; top: number; right: number; bottom: number };

// The layer's static base (x, y, scale, rotation) inside its groups as they
// stand at frame 0, the same placement inspect_layers reports as canvas_x /
// canvas_y. Keyframes are deliberately not read: a slide-in starts off-canvas
// on purpose. The box is scaled by the layer's and its ancestors' scale and,
// when rotated, replaced by the rotated box's axis-aligned bounds.
const placeOnCanvas = (
  project: Composition,
  layer: TextLayer,
  box: { width: number; height: number },
): PlacedBox => {
  const anc = composeAncestors(project, `text.${layer.id}`, 0);
  const centre = anc.apply({ x: layer.x, y: layer.y });
  const scale = (layer.scale ?? 1) * anc.scaleProduct;
  const w = box.width * scale;
  const h = box.height * scale;
  const theta = (((layer.rotation ?? 0) + anc.rotationProduct) * Math.PI) / 180;
  const cos = Math.abs(Math.cos(theta));
  const sin = Math.abs(Math.sin(theta));
  const boundsW = w * cos + h * sin;
  const boundsH = w * sin + h * cos;
  return {
    left: centre.x - boundsW / 2,
    top: centre.y - boundsH / 2,
    right: centre.x + boundsW / 2,
    bottom: centre.y + boundsH / 2,
  };
};

const fitWarning = (
  project: Composition,
  layer: TextLayer,
  measured: MeasuredTextBox,
  placed: PlacedBox,
  safe: ReturnType<typeof platformSafeAreaFor>,
  fits: TextFit,
): string => {
  const r = (n: number) => Math.round(n);
  const where = !fits.canvas
    ? `The text runs past the canvas: ${r(placed.right - placed.left)}×${r(placed.bottom - placed.top)}px on a ${project.canvas_width}×${project.canvas_height}px canvas, ` +
      `its box ${r(placed.left)}–${r(placed.right)} across and ${r(placed.top)}–${r(placed.bottom)} down.`
    : `The text runs outside the platform safe area (${safe!.x}–${safe!.x + safe!.width} across, ${safe!.y}–${safe!.y + safe!.height} down): ` +
      `its box is ${r(placed.left)}–${r(placed.right)} across and ${r(placed.top)}–${r(placed.bottom)} down.`;
  if (measured.metrics === "stored") {
    return `${where} Narrow or move the box, or lower text_size.`;
  }
  const size =
    layer.text_size && layer.text_size > 0 ? layer.text_size : DEFAULT_HUG_FONT_PX;
  const pad = layer.style?.padding ?? 0;
  const canvasFit = fittingSize(size, pad, measured, placed, {
    x: 0,
    y: 0,
    width: project.canvas_width,
    height: project.canvas_height,
  });
  const safeFit = safe ? fittingSize(size, pad, measured, placed, safe) : null;
  const sizes = [
    canvasFit === null ? null : `${canvasFit}px fits the canvas`,
    safe ? (safeFit === null ? "no size fits the safe area where it sits" : `${safeFit}px the safe area`) : null,
  ].filter((s): s is string => s !== null);
  return `${where} Add \\n line breaks or lower text_size (${sizes.join(", ")}), or move it.`;
};

// The largest text_size whose box, scaled about its current centre, stays
// inside `rect`. Glyphs scale with the size; padding does not. Null when the
// centre itself is outside the rect, where no size helps.
const fittingSize = (
  size: number,
  pad: number,
  measured: { width: number; height: number },
  placed: PlacedBox,
  rect: { x: number; y: number; width: number; height: number },
): number | null => {
  const cx = (placed.left + placed.right) / 2;
  const cy = (placed.top + placed.bottom) / 2;
  const availW = 2 * Math.min(cx - rect.x, rect.x + rect.width - cx);
  const availH = 2 * Math.min(cy - rect.y, rect.y + rect.height - cy);
  if (availW <= 2 * pad || availH <= 2 * pad) return null;
  const boundsScale = (placed.right - placed.left) / Math.max(1, measured.width);
  const glyphW = (measured.width - 2 * pad) * boundsScale;
  const glyphH = (measured.height - 2 * pad) * boundsScale;
  const factor = Math.min(
    (availW - 2 * pad * boundsScale) / Math.max(1, glyphW),
    (availH - 2 * pad * boundsScale) / Math.max(1, glyphH),
  );
  const fit = Math.floor(size * Math.min(1, factor));
  return fit >= 1 ? fit : null;
};
