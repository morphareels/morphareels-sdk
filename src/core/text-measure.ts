// The box a text layer paints at, without a browser, and whether it stays
// inside the canvas and the platform safe area.
//
// A "hug" text layer holds its font size fixed and shrink-wraps its box to
// the text, so its STORED width/height say nothing about what is painted. The
// editor measures with a real canvas (hugTextLayout in editor/src/renderer.ts);
// the headless surfaces (MCP, HTTP, the SDK, describe_video) had no measure at
// all and reported the stored box, so an agent read "900 wide" while the line
// painted 1,400px across a 1,080px canvas. This module answers from a glyph
// table measured in Chrome (src/text-metrics-data.ts, generated by
// scripts/build-text-metrics.mjs) with the same formula hugTextLayout uses,
// and composes the one report every tool result and overview carries.
//
// The per-character sum ignores kerning, so the headless width is biased
// WIDE by up to the worst sample error the generator prints (kerning only
// tightens). A line reported as fitting fits; one reported as running over
// by a few percent is at the margin.
import type { Composition, LayerStyle, TextLayer } from "./schemas.ts";
import { composeAncestors } from "./layer-space.ts";
import { platformSafeAreaFor } from "./safe-areas.ts";
import {
  DEFAULT_HUG_FONT_PX,
  DEFAULT_TEXT_FONT,
  TEXT_LINE_RATIO,
  textDisplayString,
  textFamily,
} from "./text-font.ts";
import {
  TEXT_FACES,
  TEXT_METRICS_CHARSET,
  type TextFaceMetrics,
} from "./text-metrics-data.ts";

/** Where a reported box came from: `measured` from the family's own glyphs
 *  (the table, or the editor's loaded font), `estimated` from the default
 *  family's glyphs because this family has no table, `stored` for a layer
 *  whose box is the one it stores (wrap / fit / shrink, or curved text). */
export type TextBoxMetrics = "measured" | "estimated" | "stored";

export type TextBox = {
  left: number;
  top: number;
  right: number;
  bottom: number;
  width: number;
  height: number;
  metrics: TextBoxMetrics;
  note?: string;
};

export type TextFit = { canvas: boolean; safe_area: boolean | null };

export type TextLayerReport = {
  text_box: TextBox;
  fits: TextFit;
  warning?: string;
};

/** The sentence every agent surface carries about this report. */
export const TEXT_FITS_GUIDANCE =
  "Text results and describe_video carry fits per text layer; if a warning " +
  "says the text runs past the canvas or safe area, add \\n line breaks or " +
  "lower text_size to the size named.";

/** A browser-side measurer the editor registers once the real canvas exists.
 *  It returns null when it cannot answer (the font is not loaded yet), and the
 *  glyph table answers instead, so a fallback-font measure is never reported
 *  as measured. */
export type TextMeasurer = (
  layer: TextLayer,
  style: LayerStyle | undefined,
) => { width: number; height: number } | null;

let registeredMeasurer: TextMeasurer | null = null;

export const registerTextMeasurer = (measurer: TextMeasurer | null): void => {
  registeredMeasurer = measurer;
};

// ---------------------------------------------------------------------------
// The report
// ---------------------------------------------------------------------------

export const textLayerReport = (
  project: Composition,
  layer: TextLayer,
): TextLayerReport => {
  const measured = measureTextLayer(layer, layer.style);
  const placed = placeOnCanvas(project, layer, measured);
  const safe = platformSafeAreaFor(project.canvas_width, project.canvas_height);
  const fits: TextFit = {
    canvas:
      placed.left >= 0 &&
      placed.top >= 0 &&
      placed.right <= project.canvas_width &&
      placed.bottom <= project.canvas_height,
    safe_area: safe
      ? placed.left >= safe.x &&
        placed.top >= safe.y &&
        placed.right <= safe.x + safe.width &&
        placed.bottom <= safe.y + safe.height
      : null,
  };
  const text_box: TextBox = {
    left: Math.round(placed.left),
    top: Math.round(placed.top),
    right: Math.round(placed.right),
    bottom: Math.round(placed.bottom),
    width: Math.round(placed.right - placed.left),
    height: Math.round(placed.bottom - placed.top),
    metrics: measured.metrics,
    ...(measured.note ? { note: measured.note } : {}),
  };
  if (fits.canvas && fits.safe_area !== false) return { text_box, fits };
  return {
    text_box,
    fits,
    warning: fitWarning(project, layer, measured, placed, safe, fits),
  };
};

// ---------------------------------------------------------------------------
// Measuring
// ---------------------------------------------------------------------------

export type MeasuredTextBox = {
  width: number;
  height: number;
  metrics: TextBoxMetrics;
  note?: string;
};

/** The unscaled box the layer paints: the stored box for a non-hug or curved
 *  layer, otherwise the registered browser measure or the glyph table. */
export const measureTextLayer = (
  layer: TextLayer,
  style: LayerStyle | undefined,
): MeasuredTextBox => {
  if (layer.text_autofit !== "hug" || (layer.curve ?? 0) !== 0) {
    return { width: layer.width, height: layer.height, metrics: "stored" };
  }
  const fromBrowser = registeredMeasurer?.(layer, style);
  if (fromBrowser) return { ...fromBrowser, metrics: "measured" };
  return hugBoxFromTable(layer, style);
};

const hugBoxFromTable = (
  layer: TextLayer,
  style: LayerStyle | undefined,
): MeasuredTextBox => {
  const family = textFamily(layer);
  const face = faceFor(family, layer.font_weight ?? 400, layer.font_style === "italic");
  const fontPx =
    layer.text_size && layer.text_size > 0 ? layer.text_size : DEFAULT_HUG_FONT_PX;
  const em = fontPx / 1000;
  const letterSpacing = layer.letter_spacing ?? 0;
  const lineRatio =
    layer.line_height && layer.line_height > 0 ? layer.line_height : TEXT_LINE_RATIO;
  const pad = style?.padding ?? 0;
  const lines = textDisplayString(layer)
    .split("\n")
    .map((ln) => ln.replace(/\s+$/, ""));
  let maxLineW = 0;
  for (const line of lines) {
    const chars = [...line];
    const w =
      lineAdvance(face.metrics, chars) * em +
      letterSpacing * Math.max(0, chars.length - 1);
    if (w > maxLineW) maxLineW = w;
  }
  const inkAscent = lineInkAscent(face.metrics, lines[0] ?? "") * em;
  const inkDescent = lineInkDescent(face.metrics, lines[lines.length - 1] ?? "") * em;
  const blockInk = (lines.length - 1) * fontPx * lineRatio + inkAscent + inkDescent;
  return {
    width: Math.max(1, Math.ceil(maxLineW + pad * 2)),
    height: Math.max(1, Math.ceil(blockInk + pad * 2)),
    metrics: face.exact ? "measured" : "estimated",
    ...(face.exact
      ? {}
      : {
          note: `no glyph table for "${family}": the box is estimated from ${DEFAULT_TEXT_FONT}`,
        }),
  };
};

const lineAdvance = (face: TextFaceMetrics, chars: string[]): number => {
  const advances = advancesOf(face);
  let sum = 0;
  for (const ch of chars) {
    const i = CHARSET_INDEX.get(ch);
    sum += i === undefined ? face.mean : advances[i];
  }
  return sum;
};

// Chrome's actualBoundingBoxAscent of a line is the tallest glyph in it; the
// table holds the three heights that decide it. Any character outside the
// classes (a comma, a dash) is shorter than all three.
const CAP_CLASS = /[A-Z0-9À-ÖØ-Þ!?#$%&/()[\]{}|@"'`\\]/;
const ASCENDER_CLASS = /[bdfhklt]/;
const LOWER_CLASS = /[a-zß-öø-ÿ]/;
const DESCENDER_CLASS = /[gjpqy,;()[\]{}@]/;

const lineInkAscent = (face: TextFaceMetrics, line: string): number => {
  if (line.length === 0) return face.font_ascent;
  let ascent = 0;
  if (CAP_CLASS.test(line)) ascent = face.cap_ascent;
  if (ASCENDER_CLASS.test(line)) ascent = Math.max(ascent, face.ascender_ascent);
  if (ascent === 0 && LOWER_CLASS.test(line)) ascent = face.x_ascent;
  return ascent === 0 ? face.x_ascent : ascent;
};

const lineInkDescent = (face: TextFaceMetrics, line: string): number =>
  DESCENDER_CLASS.test(line) ? face.descent : 0;

// ---------------------------------------------------------------------------
// Faces
// ---------------------------------------------------------------------------

const normFamily = (family: string): string => family.trim().toLowerCase();

const DEFAULT_FAMILY_KEY = normFamily(DEFAULT_TEXT_FONT);

/** The face to measure with: this family at the nearest weight (its italic
 *  when it has one), or the default family's nearest weight, marked inexact. */
const faceFor = (
  family: string,
  weight: number,
  italic: boolean,
): { metrics: TextFaceMetrics; exact: boolean } => {
  const key = normFamily(family);
  const own = nearestFace(key, weight, italic);
  if (own) return { metrics: own, exact: true };
  const fallback = nearestFace(DEFAULT_FAMILY_KEY, weight, italic);
  if (!fallback) {
    throw new Error(`text metrics: no glyph table for the default family ${DEFAULT_TEXT_FONT}`);
  }
  return { metrics: fallback, exact: false };
};

const nearestFace = (
  key: string,
  weight: number,
  italic: boolean,
): TextFaceMetrics | null => {
  const candidates = TEXT_FACES.filter((f) => normFamily(f.family) === key);
  if (candidates.length === 0) return null;
  const styled = candidates.filter((f) => f.italic === italic);
  const pool = styled.length > 0 ? styled : candidates;
  return pool.reduce((best, f) =>
    Math.abs(f.weight - weight) < Math.abs(best.weight - weight) ? f : best,
  );
};

export const hasGlyphTable = (family: string): boolean =>
  TEXT_FACES.some((f) => normFamily(f.family) === normFamily(family));

const CHARSET_INDEX = new Map([...TEXT_METRICS_CHARSET].map((ch, i) => [ch, i]));

const decoded = new WeakMap<TextFaceMetrics, Uint16Array>();

const advancesOf = (face: TextFaceMetrics): Uint16Array => {
  const cached = decoded.get(face);
  if (cached) return cached;
  const bytes = Uint8Array.from(atob(face.advances), (c) => c.charCodeAt(0));
  const advances = new Uint16Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 2);
  if (advances.length !== CHARSET_INDEX.size) {
    throw new Error(
      `text metrics: ${face.family} ${face.weight} has ${advances.length} advances for a ${CHARSET_INDEX.size}-character charset`,
    );
  }
  decoded.set(face, advances);
  return advances;
};

